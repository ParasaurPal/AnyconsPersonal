package com.example.export

import android.content.Context
import android.graphics.Bitmap
import android.net.Uri
import androidx.core.content.FileProvider
import com.example.data.model.IconPackUiModel
import com.example.data.model.PackIconSpec
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File
import java.io.FileOutputStream
import java.io.OutputStream
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

enum class ExportBundleFormat {
    FULL_ICON_PACK_ZIP,
    PNG_ICONS_ZIP
}

data class ExportResult(
    val fileName: String,
    val iconCount: Int,
    val shareUri: Uri? = null,
    val savedToUserUri: Boolean = false
)

object IconPackExporter {

    fun buildAppFilterXml(pack: IconPackUiModel): String {
        val included = pack.icons.filter { it.isIncluded }
        return buildString {
            appendLine("""<?xml version="1.0" encoding="utf-8"?>""")
            appendLine("<resources>")
            appendLine("    <!-- Generated by Fjord Icons: ${escapeXml(pack.name)} -->")
            for (icon in included) {
                appendLine("""    <item component="${escapeXml(icon.componentInfo)}" drawable="${escapeXml(icon.drawableName)}" />""")
            }
            appendLine("</resources>")
        }
    }

    fun buildDrawableXml(pack: IconPackUiModel): String {
        val included = pack.icons.filter { it.isIncluded }
        return buildString {
            appendLine("""<?xml version="1.0" encoding="utf-8"?>""")
            appendLine("<resources>")
            appendLine("""    <version>1</version>""")
            appendLine("""    <category title="All Icons" />""")
            for (icon in included) {
                appendLine("""    <item drawable="${escapeXml(icon.drawableName)}" />""")
            }
            appendLine("</resources>")
        }
    }

    fun buildIconPackXml(pack: IconPackUiModel): String {
        val included = pack.icons.filter { it.isIncluded }
        return buildString {
            appendLine("""<?xml version="1.0" encoding="utf-8"?>""")
            appendLine("<resources>")
            appendLine("""    <string-array name="icon_pack" translatable="false">""")
            for (icon in included) {
                appendLine("""        <item>${escapeXml(icon.drawableName)}</item>""")
            }
            appendLine("    </string-array>")
            appendLine("</resources>")
        }
    }

    fun buildPackManifestJson(pack: IconPackUiModel): String {
        val includedCount = pack.icons.count { it.isIncluded }
        return """
            {
              "name": "${pack.name.replace("\"", "'")}",
              "author": "${pack.author.replace("\"", "'")}",
              "presetStyle": "${pack.style.presetStyle.name}",
              "shape": "${pack.style.shape.name}",
              "glyphMode": "${pack.style.glyphMode.name}",
              "backgroundHex": "#${(pack.style.backgroundArgb and 0xFFFFFFL).toString(16).padStart(6, '0').uppercase()}",
              "accentHex": "#${(pack.style.accentArgb and 0xFFFFFFL).toString(16).padStart(6, '0').uppercase()}",
              "glyphHex": "#${(pack.style.glyphArgb and 0xFFFFFFL).toString(16).padStart(6, '0').uppercase()}",
              "iconCount": $includedCount,
              "resolutionPx": 192
            }
        """.trimIndent()
    }

    fun buildApplyGuide(pack: IconPackUiModel): String = buildString {
        appendLine("FJORD ICONS - LAUNCHER EXPORT GUIDE")
        appendLine("Pack: ${pack.name}")
        appendLine("Icons: ${pack.icons.count { it.isIncluded }} PNGs @ 192x192px")
        appendLine()
        appendLine("1. NIAGARA LAUNCHER:")
        appendLine("   Extract the PNGs from icons/ or res/drawable-nodpi/ into your device Downloads or Pictures.")
        appendLine("   Long-press an app in Niagara -> Tap 'Edit icon' -> Choose 'Files / Gallery' -> Select its PNG.")
        appendLine()
        appendLine("2. NOVA / LAWNCHAIR / HYPERION:")
        appendLine("   Use icons/ for per-app icon picking (Long-press icon -> Edit -> Tap icon -> Gallery / Files),")
        appendLine("   or import res/xml/appfilter.xml + res/drawable-nodpi/*.png into Icon Pack Studio or your theme builder.")
        appendLine()
        appendLine("3. SMART LAUNCHER / ACTION LAUNCHER:")
        appendLine("   Long-press any home screen icon -> Edit icon -> Select custom PNG from Files.")
    }

    suspend fun writeZipToUri(
        context: Context,
        pack: IconPackUiModel,
        format: ExportBundleFormat,
        destinationUri: Uri
    ): ExportResult = withContext(Dispatchers.IO) {
        val included = pack.icons.filter { it.isIncluded }
        context.contentResolver.openOutputStream(destinationUri)?.use { out ->
            writeZipToStream(pack, included, format, out)
        } ?: error("Unable to open destination file stream")

        ExportResult(
            fileName = suggestedZipFileName(pack, format),
            iconCount = included.size,
            savedToUserUri = true
        )
    }

    suspend fun createShareableZip(
        context: Context,
        pack: IconPackUiModel,
        format: ExportBundleFormat
    ): ExportResult = withContext(Dispatchers.IO) {
        val included = pack.icons.filter { it.isIncluded }
        val exportDir = File(context.filesDir, "exports").apply { mkdirs() }
        val fileName = suggestedZipFileName(pack, format)
        val outFile = File(exportDir, fileName)
        FileOutputStream(outFile).use { out ->
            writeZipToStream(pack, included, format, out)
        }
        val uri = FileProvider.getUriForFile(
            context,
            "${context.packageName}.fileprovider",
            outFile
        )
        ExportResult(
            fileName = fileName,
            iconCount = included.size,
            shareUri = uri
        )
    }

    suspend fun createShareableSinglePng(
        context: Context,
        pack: IconPackUiModel,
        icon: PackIconSpec,
        sizePx: Int = 512
    ): Uri = withContext(Dispatchers.IO) {
        val exportDir = File(context.filesDir, "exports").apply { mkdirs() }
        val outFile = File(exportDir, "${icon.drawableName}.png")
        val bitmap = com.example.rendering.NiagaraIconRenderer.renderToBitmap(icon, pack.style, sizePx)
        FileOutputStream(outFile).use { out ->
            bitmap.compress(Bitmap.CompressFormat.PNG, 100, out)
        }
        bitmap.recycle()
        FileProvider.getUriForFile(
            context,
            "${context.packageName}.fileprovider",
            outFile
        )
    }

    suspend fun writeSinglePngToUri(
        context: Context,
        pack: IconPackUiModel,
        icon: PackIconSpec,
        destinationUri: Uri,
        sizePx: Int = 512
    ) = withContext(Dispatchers.IO) {
        val bitmap = com.example.rendering.NiagaraIconRenderer.renderToBitmap(icon, pack.style, sizePx)
        try {
            context.contentResolver.openOutputStream(destinationUri)?.use { out ->
                bitmap.compress(Bitmap.CompressFormat.PNG, 100, out)
            } ?: error("Unable to open destination file stream")
        } finally {
            bitmap.recycle()
        }
    }

    fun suggestedZipFileName(pack: IconPackUiModel, format: ExportBundleFormat): String {
        val slug = pack.name.lowercase().replace(Regex("[^a-z0-9]+"), "_").trim('_').ifEmpty { "fjord_pack" }
        return when (format) {
            ExportBundleFormat.FULL_ICON_PACK_ZIP -> "${slug}_icon_pack.zip"
            ExportBundleFormat.PNG_ICONS_ZIP -> "${slug}_png_icons.zip"
        }
    }

    private fun writeZipToStream(
        pack: IconPackUiModel,
        included: List<PackIconSpec>,
        format: ExportBundleFormat,
        out: OutputStream
    ) {
        ZipOutputStream(out).use { zip ->
            val usedNames = HashSet<String>()
            for (icon in included) {
                var baseName = icon.drawableName
                var suffix = 2
                while (!usedNames.add(baseName)) {
                    baseName = "${icon.drawableName}_$suffix"
                    suffix++
                }
                val entryPath = when (format) {
                    ExportBundleFormat.FULL_ICON_PACK_ZIP -> "res/drawable-nodpi/$baseName.png"
                    ExportBundleFormat.PNG_ICONS_ZIP -> "icons/$baseName.png"
                }
                zip.putNextEntry(ZipEntry(entryPath))
                val bmp = com.example.rendering.NiagaraIconRenderer.renderToBitmap(icon, pack.style, 192)
                bmp.compress(Bitmap.CompressFormat.PNG, 100, zip)
                bmp.recycle()
                zip.closeEntry()
            }

            if (format == ExportBundleFormat.FULL_ICON_PACK_ZIP) {
                writeTextEntry(zip, "res/xml/appfilter.xml", buildAppFilterXml(pack))
                writeTextEntry(zip, "res/xml/drawable.xml", buildDrawableXml(pack))
                writeTextEntry(zip, "res/xml/iconpack.xml", buildIconPackXml(pack))
                writeTextEntry(zip, "pack_manifest.json", buildPackManifestJson(pack))
            }
            writeTextEntry(zip, "APPLY_GUIDE.txt", buildApplyGuide(pack))
        }
    }

    private fun writeTextEntry(zip: ZipOutputStream, name: String, content: String) {
        zip.putNextEntry(ZipEntry(name))
        zip.write(content.toByteArray(Charsets.UTF_8))
        zip.closeEntry()
    }

    private fun escapeXml(value: String): String {
        return value
            .replace("&", "&amp;")
            .replace("\"", "&quot;")
            .replace("<", "&lt;")
            .replace(">", "&gt;")
    }
}
